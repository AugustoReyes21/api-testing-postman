import SwaggerParser from '@apidevtools/swagger-parser';
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const file = 'openapi/openapi.json';
const document = JSON.parse(readFileSync(file));
const expected = JSON.parse(JSON.stringify((await import('./specification.mjs')).specification));
if (JSON.stringify(document) !== JSON.stringify(expected)) throw new Error('OpenAPI generado difiere de specification.mjs. Ejecute npm run generate.');
await SwaggerParser.validate(file);
const ajv = new Ajv2020({ strict: true, allErrors: true }); addFormats(ajv);
for (const schema of Object.values(document.components.schemas)) ajv.compile(schema);
const collection = JSON.parse(readFileSync('collections/pedidos.postman_collection.json'));
const cases = [...new Set(collection.item.map(i => i.name.match(/^TC-\d+/)?.[0]).filter(Boolean))].sort();
if (cases.length !== 18) throw new Error('Cobertura de casos incompleta.');
const environment = JSON.parse(readFileSync('environments/pedidos.example.postman_environment.json'));
if (environment.values.some(v => /password|token/i.test(v.key) && v.value !== '')) throw new Error('El ambiente de ejemplo contiene valores sensibles.');
const report = { at: new Date().toISOString(), openapi: document.openapi, validator: '@apidevtools/swagger-parser + Ajv2020 (esquemas)', valid: true, schemaCount: Object.keys(document.components.schemas).length, operationCount: Object.values(document.paths).flatMap(p=>Object.keys(p).filter(k=>['get','post','put','delete'].includes(k))).length, collectionFormat: '2.1.0', requestCount: collection.item.length, cases };
mkdirSync('evidence', {recursive:true}); writeFileSync('evidence/validation.json', JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));
